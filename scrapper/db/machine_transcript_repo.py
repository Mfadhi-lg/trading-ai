@atomic_repository('documents')
def existing_machine_run(
    conn: sqlite3.Connection,
    *,
    source_media_content_id: int,
    engine: str,
    engine_version: str,
    model_version: str,
    options: dict[str, Any],
) -> sqlite3.Row | None:
    return execute(conn,
        """SELECT * FROM machine_transcription_runs
           WHERE source_media_content_id=? AND engine=? AND engine_version=?
             AND model_version=? AND options_json=?""",
        (
            source_media_content_id,
            engine,
            engine_version,
            model_version,
            canonical_json(options),
        ),
    ).fetchone()


def _generated_payload(
    *,
    transcript_artifact_id: int,
    recording_artifact_id: int,
    normalization_id: int,
    source_media_sha256: str,
    source_recording_sha256: str,
    source_duration_ms: int,
    engine: str,
    engine_version: str,
    model_version: str,
    options: dict[str, Any],
    parsed: ValidatedMachineTranscript,
) -> dict[str, Any]:
    return {
        "schema_version": "1.0.0",
        "origin": "machine_generated",
        "transcript_artifact_id": transcript_artifact_id,
        "recording_artifact_id": recording_artifact_id,
        "normalization_id": normalization_id,
        "source_media_sha256": source_media_sha256,
        "source_recording_sha256": source_recording_sha256,
        "source_duration_ms": source_duration_ms,
        "engine": engine,
        "engine_version": engine_version,
        "model_version": model_version,
        "options": options,
        "detected_language": parsed.language,
        "language_confidence": parsed.language_confidence,
        "duration_coverage": parsed.duration_coverage,
        "segments": [row.to_dict(position) for position, row in enumerate(parsed.segments)],
    }


@atomic_repository('documents')
def persist_machine_transcript(
    conn: sqlite3.Connection,
    *,
    transcript_artifact_id: int,
    recording_artifact_id: int,
    normalization_id: int,
    source_media_content_id: int,
    source_media_sha256: str,
    source_recording_content_id: int,
    source_recording_sha256: str,
    source_duration_ms: int,
    engine: str,
    engine_version: str,
    model_version: str,
    options: dict[str, Any],
    comparison_requested: bool,
    parsed: ValidatedMachineTranscript,
    started_at_utc: str,
    completed_at_utc: str,
    snapshot_root: Path = DOCUMENT_CONTENT_SNAPSHOTS,
) -> int:
    """Persist generated bytes, transcript rows, validations and preference atomically."""

    options_json = canonical_json(options)
    generated = _generated_payload(
        transcript_artifact_id=transcript_artifact_id,
        recording_artifact_id=recording_artifact_id,
        normalization_id=normalization_id,
        source_media_sha256=source_media_sha256,
        source_recording_sha256=source_recording_sha256,
        source_duration_ms=source_duration_ms,
        engine=engine,
        engine_version=engine_version,
        model_version=model_version,
        options=options,
        parsed=parsed,
    )
    body = (json.dumps(generated, indent=2, sort_keys=True) + "\n").encode("utf-8")
    structurally_storable = all(
        bool(row.text_raw.strip())
        and row.start_ms >= 0
        and row.end_ms >= row.start_ms
        for row in parsed.segments
    )
    transcript_id: int | None = None
    error: dict[str, Any] = {}
    with repository_transaction(conn):
        blob_id, _ = store_response_blob(
            conn,
            body=body,
            media_type="application/json",
            observed_at_utc=completed_at_utc,
            snapshot_root=snapshot_root,
        )
        content_id = register_artifact_content(
            conn,
            artifact_id=transcript_artifact_id,
            blob_id=blob_id,
            media_type="application/json",
            is_official=False,
            content_origin="generated_derivative",
            created_at_utc=completed_at_utc,
        )
        if structurally_storable:
            transcript_engine = f"{engine}@{engine_version}"
            cursor = execute(conn,
                """INSERT INTO transcripts
                   (artifact_id, content_id, extraction_id, origin,
                    source_media_content_id, language, engine, model_version,
                    options_json, document_marker_raw, document_marker_page,
                    created_at_utc, validation_status, segment_count,
                    page_start, page_end, prepared_segment_count, qa_segment_count,
                    unknown_segment_count, error_json)
                   VALUES (?, ?, NULL, 'machine_generated', ?, ?, ?, ?, ?, NULL,
                           NULL, ?, ?, ?, NULL, NULL, 0, 0, ?, '{}')""",
                (
                    transcript_artifact_id,
                    content_id,
                    source_media_content_id,
                    parsed.language,
                    transcript_engine,
                    model_version,
                    options_json,
                    completed_at_utc,
                    parsed.status,
                    len(parsed.segments),
                    len(parsed.segments),
                ),
             returning='transcript_id')
            transcript_id = generated_id(cursor, 'transcript_id')
            executemany(conn,
                """INSERT INTO transcript_segments
                   (transcript_id, segment_position, page_start, page_end,
                    element_start, element_end, start_ms, end_ms, speaker_raw,
                    speaker_normalized, text_raw, confidence, section_kind,
                    text_origin, source_fragments_json, uncertainty_json)
                   VALUES (?, ?, NULL, NULL, NULL, NULL, ?, ?, 'unknown',
                           'unknown', ?, ?, 'unknown', 'machine_generated', '[]', ?)""",
                [
                    (
                        transcript_id,
                        position,
                        row.start_ms,
                        row.end_ms,
                        row.text_raw,
                        row.confidence,
                        canonical_json(row.uncertainty),
                    )
                    for position, row in enumerate(parsed.segments)
                ],
            )
            executemany(conn,
                """INSERT INTO transcript_validations
                   (transcript_id, rule_code, severity, status, expected_value,
                    actual_value, details_json)
                   VALUES (?, ?, ?, ?, ?, ?, ?)""",
                [
                    (
                        transcript_id,
                        row.rule_code,
                        row.severity,
                        "passed" if row.passed else "failed",
                        canonical_json(row.expected),
                        canonical_json(row.actual),
                        canonical_json(row.details),
                    )
                    for row in parsed.validations
                ],
            )
        else:
            error = {
                "type": "InvalidSegmentStructure",
                "message": "Engine output cannot satisfy transcript segment constraints",
            }
        cursor = execute(conn,
            """INSERT INTO machine_transcription_runs
               (transcript_artifact_id, recording_artifact_id, normalization_id,
                source_media_content_id, source_media_sha256,
                source_media_duration_ms, source_recording_content_id,
                source_recording_sha256, engine, engine_version, model_version,
                options_json, comparison_requested, gate_reason,
                detected_language, language_confidence, duration_coverage,
                started_at_utc, completed_at_utc, run_status,
                generated_content_id, transcript_id, error_json)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?,
                       ?, ?, ?, ?)""",
            (
                transcript_artifact_id,
                recording_artifact_id,
                normalization_id,
                source_media_content_id,
                source_media_sha256,
                source_duration_ms,
                source_recording_content_id,
                source_recording_sha256,
                engine,
                engine_version,
                model_version,
                options_json,
                int(comparison_requested),
                "human_comparison" if comparison_requested else "no_usable_official",
                parsed.language,
                parsed.language_confidence,
                parsed.duration_coverage,
                started_at_utc,
                completed_at_utc,
                parsed.status if transcript_id is not None else "failed",
                content_id,
                transcript_id,
                canonical_json(error),
            ),
         returning='transcription_run_id')
        run_id = generated_id(cursor, 'transcription_run_id')
        if (
            transcript_id is not None
            and parsed.status == "accepted"
            and not comparison_requested
        ):
            execute(conn,
                """INSERT INTO preferred_transcripts
                   (artifact_id, transcript_id, updated_at_utc)
                   VALUES (?, ?, ?)
                   ON CONFLICT(artifact_id) DO UPDATE SET
                     transcript_id=excluded.transcript_id,
                     updated_at_utc=excluded.updated_at_utc""",
                (transcript_artifact_id, transcript_id, completed_at_utc),
            )
            execute(conn,
                """UPDATE document_artifacts
                   SET preferred_content_id=?, acquisition_status='validated',
                       transcript_preference_status='machine_preferred'
                   WHERE artifact_id=?""",
                (content_id, transcript_artifact_id),
            )
    return run_id


@atomic_repository('documents')
def persist_machine_transcription_failure(
    conn: sqlite3.Connection,
    *,
    transcript_artifact_id: int,
    recording_artifact_id: int,
    normalization_id: int,
    source_media_content_id: int,
    source_media_sha256: str,
    source_media_duration_ms: int,
    source_recording_content_id: int,
    source_recording_sha256: str,
    engine: str,
    engine_version: str,
    model_version: str,
    options: dict[str, Any],
    comparison_requested: bool,
    started_at_utc: str,
    completed_at_utc: str,
    error: dict[str, Any],
) -> int:
    with repository_transaction(conn):
        cursor = execute(conn,
            """INSERT INTO machine_transcription_runs
               (transcript_artifact_id, recording_artifact_id, normalization_id,
                source_media_content_id, source_media_sha256,
                source_media_duration_ms, source_recording_content_id,
                source_recording_sha256, engine, engine_version, model_version,
                options_json, comparison_requested, gate_reason, started_at_utc,
                completed_at_utc, run_status, error_json)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'failed', ?)""",
            (
                transcript_artifact_id,
                recording_artifact_id,
                normalization_id,
                source_media_content_id,
                source_media_sha256,
                source_media_duration_ms,
                source_recording_content_id,
                source_recording_sha256,
                engine,
                engine_version,
                model_version,
                canonical_json(options),
                int(comparison_requested),
                "human_comparison" if comparison_requested else "no_usable_official",
                started_at_utc,
                completed_at_utc,
                canonical_json(error),
            ),
         returning='transcription_run_id')
    return generated_id(cursor, 'transcription_run_id')


@atomic_repository('documents')
def machine_run_payload(conn: sqlite3.Connection, run_id: int) -> dict[str, Any]:
    row = execute(conn,
        "SELECT * FROM machine_transcription_runs WHERE transcription_run_id=?",
        (run_id,),
    ).fetchone()
    if row is None:
        raise ValueError(f"Unknown machine transcription run: {run_id}")

    def content(content_id: int) -> dict[str, Any]:
        item = execute(conn,
            """SELECT content.*, blob.local_path FROM artifact_contents AS content
               JOIN response_blobs AS blob USING (blob_id)
               WHERE content.content_id=?""",
            (content_id,),
        ).fetchone()
        if item is None:
            raise RuntimeError(f"Missing transcription content: {content_id}")
        return {
            "content_id": int(item["content_id"]),
            "media_type": item["media_type"],
            "content_sha256": item["content_sha256"],
            "byte_size": int(item["byte_size"]),
            "is_official": bool(item["is_official"]),
            "content_origin": item["content_origin"],
            "local_path": item["local_path"],
        }

    transcript = (
        transcript_payload(conn, int(row["transcript_id"]))
        if row["transcript_id"] is not None
        else None
    )
    return {
        "transcription_run_id": run_id,
        "transcript_artifact_id": int(row["transcript_artifact_id"]),
        "recording_artifact_id": int(row["recording_artifact_id"]),
        "normalization_id": int(row["normalization_id"]),
        "source_media": content(int(row["source_media_content_id"])),
        "source_media_duration_ms": int(row["source_media_duration_ms"]),
        "source_recording": content(int(row["source_recording_content_id"])),
        "engine": row["engine"],
        "engine_version": row["engine_version"],
        "model_version": row["model_version"],
        "options": json.loads(row["options_json"]),
        "comparison_requested": bool(row["comparison_requested"]),
        "gate_reason": row["gate_reason"],
        "detected_language": row["detected_language"],
        "language_confidence": row["language_confidence"],
        "duration_coverage": row["duration_coverage"],
        "started_at_utc": row["started_at_utc"],
        "completed_at_utc": row["completed_at_utc"],
        "run_status": row["run_status"],
        "generated_content": (
            content(int(row["generated_content_id"]))
            if row["generated_content_id"] is not None
            else None
        ),
        "transcript": transcript,
        "error": json.loads(row["error_json"]),
    }
