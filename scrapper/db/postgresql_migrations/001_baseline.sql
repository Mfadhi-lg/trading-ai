      AND content.content_origin='publisher_original'
      AND extraction.extraction_id=NEW.extraction_id
      AND extraction.extraction_status='ok'
  ) THEN RAISE EXCEPTION USING MESSAGE = 'official transcript requires usable official extraction', ERRCODE = '23514'; END IF;
  IF NEW.origin='machine_generated' AND NOT EXISTS (
    SELECT 1 FROM artifact_contents AS content
    WHERE content.content_id=NEW.content_id
      AND content.artifact_id=NEW.artifact_id
      AND content.is_official=0
      AND content.content_origin='generated_derivative'
  ) THEN RAISE EXCEPTION USING MESSAGE = 'machine transcript requires generated derivative content', ERRCODE = '23514'; END IF;
RETURN NEW;
END;
$trigger$;
CREATE TRIGGER "transcript_identity_insert_guard" BEFORE INSERT ON "transcripts"
FOR EACH ROW EXECUTE FUNCTION "transcript_identity_insert_guard"();

CREATE FUNCTION "transcript_segment_identity_guard"() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $trigger$
BEGIN
IF NOT EXISTS (
    SELECT 1 FROM transcripts AS transcript
    WHERE transcript.transcript_id=NEW.transcript_id
      AND (
        (transcript.origin='official' AND NEW.page_start IS NOT NULL
         AND NEW.start_ms IS NULL AND NEW.text_origin IN ('native', 'ocr', 'mixed'))
        OR
        (transcript.origin='machine_generated' AND NEW.page_start IS NULL
         AND NEW.start_ms IS NOT NULL AND NEW.text_origin='machine_generated')
      )
  ) THEN RAISE EXCEPTION USING MESSAGE = 'transcript segment origin mismatch', ERRCODE = '23514'; END IF;
RETURN NEW;
END;
$trigger$;
CREATE TRIGGER "transcript_segment_identity_guard" BEFORE INSERT ON "transcript_segments"
FOR EACH ROW EXECUTE FUNCTION "transcript_segment_identity_guard"();

