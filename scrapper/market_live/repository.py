"""Separate native live evidence repository. Runtime never provisions a target."""
import hashlib
import json
import os
from pathlib import Path
from types import SimpleNamespace

from scrapper.db.postgresql import PostgreSQLSettings, _configure, _connection_kwargs
from scrapper.db.postgresql_schema import validate_schema_name
from scrapper.db.candle_inventory_transfer import catalog

DDL = '''CREATE TABLE frames(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_ms BIGINT, received_at TEXT, sha256 TEXT, raw_path TEXT);
CREATE TABLE observations(
    frame_id BIGINT NOT NULL REFERENCES frames(id), instrument TEXT NOT NULL,
    start TEXT NOT NULL, provider_ms BIGINT, received_at TEXT,
    completed INTEGER CHECK(completed IN (0,1)), payload TEXT,
    PRIMARY KEY(frame_id,instrument,start));
CREATE INDEX observation_lookup ON observations(instrument,start,provider_ms);
CREATE TABLE live_identity(root TEXT PRIMARY KEY, version TEXT NOT NULL);
'''
VERSION = 'live_evidence_v1'
MARKER = '.live-target.json'


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, default=str).encode()).hexdigest()


def contract(conn, schema, root):
    from psycopg import sql
    conn.execute(sql.SQL('SET search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
    identity = conn.execute('''SELECT (SELECT system_identifier::text FROM pg_control_system()),
        (SELECT oid::text FROM pg_database WHERE datname=current_database()),
        (SELECT oid::text FROM pg_namespace WHERE nspname=%s)''', (schema,)).fetchone()
    rows = conn.execute(sql.SQL('SELECT * FROM {}.live_identity').format(sql.Identifier(schema))).fetchall()
    if rows != [(str(Path(root).resolve()), VERSION)]:
        raise RuntimeError('Live root/version mismatch')
    return dict(identity=list(identity), schema=schema, root=str(Path(root).resolve()),
                catalog=fingerprint([catalog(conn, schema), conn.execute(
                    "SELECT c.relname,a.attname,a.attidentity,a.attgenerated FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=%s AND a.attnum>0 AND NOT a.attisdropped ORDER BY 1,2", (schema,)).fetchall(), conn.execute(
                    "SELECT c.relname,s.seqstart,s.seqincrement,s.seqmax,s.seqmin,s.seqcache,s.seqcycle FROM pg_sequence s JOIN pg_class c ON c.oid=s.seqrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=%s ORDER BY 1", (schema,)).fetchall()]), version=VERSION)


def provision(settings, schema, root, role):
    """Explicit admin API for a NEW schema; returns the reviewable target pin.

    Call only for an authorized isolated target. Does not select/activate it.
    Runtime role must be a separately managed restricted login.
    """
    from psycopg import sql
    import psycopg
    validate_schema_name(schema)
    with psycopg.connect(settings.dsn, **_connection_kwargs(settings)) as conn:
        _configure(conn)
        with conn.transaction():
            conn.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
            conn.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
            conn.execute(DDL)
            conn.execute('INSERT INTO live_identity VALUES (%s,%s)', (str(Path(root).resolve()), VERSION))
            conn.execute(sql.SQL('GRANT USAGE ON SCHEMA {} TO {}').format(sql.Identifier(schema), sql.Identifier(role)))
            conn.execute(sql.SQL('GRANT SELECT ON ALL TABLES IN SCHEMA {} TO {}').format(sql.Identifier(schema), sql.Identifier(role)))
            for table in ('frames','observations'):
                conn.execute(sql.SQL('GRANT INSERT ON {}.{} TO {}').format(sql.Identifier(schema), sql.Identifier(table), sql.Identifier(role)))
            conn.execute(sql.SQL('GRANT USAGE ON ALL SEQUENCES IN SCHEMA {} TO {}').format(sql.Identifier(schema), sql.Identifier(role)))
            # Required only for verifying the cluster identifier, not general admin.
            conn.execute(sql.SQL('GRANT EXECUTE ON FUNCTION pg_control_system() TO {}').format(sql.Identifier(role)))
            return contract(conn, schema, root)


def selection(config):
    value = (config or {}).get('live_store', {'backend':'sqlite'})
    if not isinstance(value, dict) or value.get('backend') not in ('sqlite','postgresql'):
        raise ValueError('Explicit live_store backend must be sqlite or postgresql')
    if value['backend'] == 'postgresql':
        validate_schema_name(value.get('schema',''))
        if not value.get('target') or not value.get('database_url_env'):
            raise ValueError('Native live store requires an explicit target pin and credential environment name')
    return value


class NativeRepository:
    def __init__(self, root, config, *, lane='stream'):
        import psycopg
        from psycopg import sql
        from psycopg.rows import tuple_row
        if lane not in ('stream','recovery','reader'):
            raise ValueError('Unknown live writer lane')
        self.raw = None
        self.transaction = None
        value = selection(config)
        schema = value['schema']
        settings = PostgreSQLSettings(os.environ.get(value['database_url_env'],''))
        try:
            self.raw = psycopg.connect(settings.dsn, row_factory=tuple_row, **_connection_kwargs(settings))
            _configure(self.raw)
            for name, number in (('statement_timeout',settings.statement_timeout_ms),('lock_timeout',settings.lock_timeout_ms)):
                self.raw.execute('SELECT set_config(%s,%s,false)',(name,str(number)))
            self.raw.execute(sql.SQL('SET search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
            privileged = self.raw.execute("SELECT EXISTS(SELECT 1 FROM pg_roles WHERE (rolsuper OR rolcreatedb OR rolcreaterole) AND pg_has_role(current_user,oid,'MEMBER'))").fetchone()[0]
            if privileged:
                raise RuntimeError('Restricted live runtime login required')
            if self.raw.execute("SELECT has_schema_privilege(%s,'CREATE')",(schema,)).fetchone()[0]:
                raise RuntimeError('Live runtime cannot create schema objects')
            if self.raw.execute("SELECT has_sequence_privilege(%s,'UPDATE')",(schema+'.frames_id_seq',)).fetchone()[0]:
                raise RuntimeError('Live runtime cannot reset generated IDs')
            if contract(self.raw, schema, root) != value['target']:
                raise RuntimeError('Live target identity/schema mismatch')
            for table in ('frames','observations','live_identity'):
                if self.raw.execute("SELECT has_any_column_privilege(%s,'UPDATE')",(schema+'.'+table,)).fetchone()[0]:
                    raise RuntimeError('Live runtime requires append-only column permissions')
                for privilege in ('UPDATE','DELETE','TRUNCATE','TRIGGER'):
                    if self.raw.execute('SELECT has_table_privilege(%s,%s)',(schema+'.'+table,privilege)).fetchone()[0]:
                        raise RuntimeError('Live runtime requires append-only permissions')
            if lane != 'reader':
                if not self.raw.execute('SELECT pg_try_advisory_lock(hashtextextended(%s,0))',('live:'+schema+':'+lane,)).fetchone()[0]:
                    raise RuntimeError('Live writer busy')
            if json.loads((Path(root)/MARKER).read_text()) != value['target']:
                raise RuntimeError('Live target marker changed during admission')
            self.read_only = lane == 'reader'
            if self.read_only:
                self.raw.execute('SET default_transaction_read_only=on')
        except psycopg.Error:
            self.close()
            raise RuntimeError('Live PostgreSQL unavailable or permission denied') from None
        except BaseException:
            self.close()
            raise

    def __enter__(self):
        self.transaction = self.raw.transaction()
        self.transaction.__enter__()
        return self

    def __exit__(self, *args):
        return self.transaction.__exit__(*args)

    def execute(self, query, params=()):
        # Only the fixed statements in LiveStore use this internal adapter.
        query = query.replace('?', '%s')
        generated = query.startswith('INSERT INTO frames(')
        if generated:
            query += ' RETURNING id'
        cursor = self.raw.execute(query, params)
        return SimpleNamespace(lastrowid=cursor.fetchone()[0]) if generated else cursor

    def close(self):
        if self.raw is not None:
            self.raw.close()


def open_store(root, config=None, *, lane='stream'):
    value = selection(config)
    marker = Path(root) / MARKER
    if value['backend'] == 'postgresql':
        # An operator-selected marker is mandatory; config alone cannot activate.
        if json.loads(marker.read_text()) != value['target']:
            raise RuntimeError('Live target marker mismatch')
        return NativeRepository(root, config, lane=lane)
    if marker.exists():
        raise RuntimeError('Live native target selected; SQLite fallback refused')
    if lane == 'reader':
        import sqlite3
        conn = sqlite3.connect((Path(root).resolve()/'live.sqlite3').as_uri()+'?mode=ro',uri=True)
        conn.execute('PRAGMA query_only=ON')
        return conn
    return None
