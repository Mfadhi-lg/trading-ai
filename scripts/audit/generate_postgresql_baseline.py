"""Generate the reviewed PostgreSQL baseline from synthetic SQLite migrations.

This deliberately supports only the DDL forms in the frozen SQLite lineage.
It never reads an application database. Generated SQL is committed and reviewed;
the runtime migration runner never performs dialect translation.
"""
import hashlib
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "scrapper/db/postgresql_migrations"
# PG001 is a frozen baseline, not a rolling export of future SQLite schemas.
LAST_SQLITE_VERSION = 76


def identifier(value):
    return '"' + value.replace('"', '""') + '"'


def split_definitions(body):
    # SQL strings and quoted identifiers are atomic; commas in CHECK/UNIQUE
    # expressions or literal strings must not separate column definitions.
    tokens = re.findall(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|--[^\n]*|[^'\"]", body)
    parts, current, depth = [], [], 0
    for token in tokens:
        if token.startswith("--"):
            continue
        if token == "(":
            depth += 1
        elif token == ")":
            depth -= 1
        if token == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(token)
    parts.append("".join(current).strip())
    return parts


def convert_types(definition):
    return re.sub(
        r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|\bINTEGER\b|\bREAL\b",
        lambda m: {"INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION"}.get(m[0], m[0]),
        definition, flags=re.I,
    )


def table_sql(conn, name, source):
    match = re.fullmatch(r"CREATE TABLE\s+(?:IF NOT EXISTS\s+)?(?:\"[^\"]+\"|\w+)\s*\((.*)\)\s*(?:WITHOUT ROWID)?", source, re.S | re.I)
    if not match:
        raise ValueError(f"Unsupported table DDL: {name}")
    columns = list(conn.execute(f"PRAGMA table_info({identifier(name)})"))
    foreign_keys = list(conn.execute(f"PRAGMA foreign_key_list({identifier(name)})"))
    pk = [col[1] for col in columns if col[5]]
    generated = pk[0] if len(pk) == 1 and any(col[1] == pk[0] and col[2] == "INTEGER" for col in columns) and not any(fk[3] == pk[0] for fk in foreign_keys) else None
    definitions = []
    for definition in split_definitions(match[1]):
        if re.match(r"FOREIGN KEY\b", definition, re.I):
            continue
        definition = re.sub(
            r'\bREFERENCES\s+(?:"[^\"]+"|\w+)\s*\([^)]*\)(?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:SET NULL|SET DEFAULT|NO ACTION|RESTRICT|CASCADE))*',
            "", definition, flags=re.I,
        )
        definition = convert_types(definition)
        if generated and re.match(rf'"?{re.escape(generated)}"?\s+BIGINT\b', definition):
            definition = re.sub(r"\bBIGINT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY", definition, count=1)
        definitions.append(definition)
    create = f"CREATE TABLE {identifier(name)} (\n    " + ",\n    ".join(definitions) + "\n);"
    alters = []
    for key_id in sorted({fk[0] for fk in foreign_keys}):
        keys = sorted((fk for fk in foreign_keys if fk[0] == key_id), key=lambda fk: fk[1])
        parent, on_update, on_delete = keys[0][2], keys[0][5], keys[0][6]
        local = ", ".join(identifier(fk[3]) for fk in keys)
        remote = ", ".join(identifier(fk[4]) for fk in keys)
        alters.append(f"ALTER TABLE {identifier(name)} ADD FOREIGN KEY ({local}) REFERENCES {identifier(parent)} ({remote}) ON UPDATE {on_update} ON DELETE {on_delete} DEFERRABLE INITIALLY IMMEDIATE;")
    return create, alters


def trigger_sql(name, source):
    match = re.fullmatch(r"CREATE TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(INSERT|UPDATE(?: OF [\w, ]+)?)\s+ON\s+(\w+)\s*(?:WHEN\s+(.*?))?\s*BEGIN\s*(.*?)\s*END", source, re.S)
    if not match:
        raise ValueError(f"Unsupported trigger DDL: {name}")
    _, timing, event, table, condition, body = match.groups()
    body = re.sub(r"SELECT CASE WHEN (.*?) THEN RAISE\(ABORT, ('(?:''|[^'])*')\) END;", r"IF \1 THEN RAISE EXCEPTION USING MESSAGE = \2, ERRCODE = '23514'; END IF;", body, flags=re.S)
    body = re.sub(r"SELECT RAISE\(ABORT, ('(?:''|[^'])*')\);", r"RAISE EXCEPTION USING MESSAGE = \1, ERRCODE = '23514';", body)
    if "RAISE(ABORT" in body or "SELECT CASE" in body:
        raise ValueError(f"Untranslated trigger body: {name}")
    if condition:
        body = f"IF {condition} THEN\n{body}\nEND IF;"
    # Runtime trigger lookups resolve to the schema that owns the function,
    # independent of caller-controlled search_path.
    return f"""CREATE FUNCTION {identifier(name)}() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $trigger$
BEGIN
{body}
RETURN NEW;
END;
$trigger$;
CREATE TRIGGER {identifier(name)} {timing} {event} ON {identifier(table)}
FOR EACH ROW EXECUTE FUNCTION {identifier(name)}();"""


def generate():
    conn = sqlite3.connect(":memory:")
    sources = {}
    for path in sorted((ROOT / "scrapper/db/migrations").glob("*.sql")):
        if int(path.name[:3]) > LAST_SQLITE_VERSION:
            continue
        content = path.read_bytes()
        sources[path.name] = hashlib.sha256(content).hexdigest()
        conn.executescript(content.decode())
    if len(sources) != LAST_SQLITE_VERSION:
        raise ValueError("Expected the frozen SQLite 001-076 source inventory")
    objects = list(conn.execute("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name"))
    sections, foreign_keys = [], []
    for kind, name, _, source in objects:
        if kind == "table":
            create, alters = table_sql(conn, name, source)
            sections.append(create)
            foreign_keys.extend(alters)
    sections.extend(foreign_keys)
    sections.extend(source + ";" for kind, _, _, source in objects if kind == "index")
    # SQLite allows forward view references; PostgreSQL needs dependency order.
    pending = {name: source for kind, name, _, source in objects if kind == "view"}
    while pending:
        ready = [name for name, source in pending.items() if not any(re.search(rf"\b{re.escape(other)}\b", source, re.I) for other in pending if other != name)]
        if not ready:
            raise ValueError("Cyclic view dependencies")
        for name in ready:
            source = pending.pop(name)
            if name == "artifact_retry_coverage":
                source = source.replace("JOIN companies AS company USING (company_id)", "JOIN companies AS company ON company.company_id=expectation.company_id")
            sections.append(source + ";")
    sections.extend(trigger_sql(name, source) for kind, name, _, source in objects if kind == "trigger")
    sql = "-- PostgreSQL 16 baseline; generated from synthetic SQLite 001-076.\n-- Raw decimal/timestamp/JSON strings stay TEXT. No operational seed rows.\n\n" + "\n\n".join(sections) + "\n"
    catalog = [(kind, name, source) for kind, name, _, source in objects]
    manifest = {"sqlite_schema_sha256": hashlib.sha256(json.dumps(catalog, ensure_ascii=True, separators=(",", ":")).encode()).hexdigest(), "sqlite_sources": sources, "objects": {kind: sorted(name for typ, name, _, _ in objects if typ == kind) for kind in ("table", "index", "view", "trigger")}, "migrations": {"001_baseline.sql": hashlib.sha256(sql.encode()).hexdigest()}}
    conn.close()
    return sql, manifest


if __name__ == "__main__":
    sql, manifest = generate()
    OUTPUT.mkdir(exist_ok=True)
    (OUTPUT / "001_baseline.sql").write_text(sql)
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
